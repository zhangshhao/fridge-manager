  seasonings.has(canonicalIngredient(name));

export function ingredientChoices(value: string): string[] {
  return [
    ...new Set(
      value
        .split(/[/／或、]/)
        .map(canonicalIngredient)
        .filter(Boolean),
    ),
  ];
}
