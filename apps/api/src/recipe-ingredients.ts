export function cleanIngredientName(value: string): string {
  return value
    .normalize("NFKC")
    .toLowerCase()
    .replace(/\s+/g, "")
    .replace(/[\p{Extended_Pictographic}\uFE0F]/gu, "")
    .replace(/[（(][^）)]*[）)]/g, "")
    .replace(/[，,：:。；;].*$/, "")
    .replace(/^(?:新鲜的?|洗净的?|去皮的?|去骨的?|切好的?|适量的?)/, "")
    .replace(/(?:适量|少许|若干|备用|切末|切片|切丝|切块)$/, "")
    .trim();
}
const aliases = new Map(
  groups.flatMap((g) => g.map((name) => [name, g[0]] as const)),
);
export const canonicalIngredient = (value: string) => {
  const name = cleanIngredientName(value);
  return aliases.get(name) || name;
};

